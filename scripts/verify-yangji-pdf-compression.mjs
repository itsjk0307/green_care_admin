/**
 * Rebuild Yangji Pine PDF with current mapWorkPdf.ts (MEDIUM compression),
 * compare old vs new size from IndexedDB.
 */
import { chromium } from 'playwright'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const ORIGIN = process.env.GC_DEV_ORIGIN ?? 'http://localhost:5173'
const REPORT_ID = 'b1ce2491-29dc-48b5-9b86-c977e65b61e1'
const LIMIT = 20 * 1024 * 1024
const OUT = path.join(os.tmpdir(), 'yangji-pine-compression-check.pdf')

const chromeDefault = path.join(
  os.homedir(),
  'AppData/Local/Google/Chrome/User Data/Default',
)
const profileDir = path.join(os.tmpdir(), 'gc-pw-verify-profile')

function copyDir(src, dest) {
  if (!fs.existsSync(src)) return false
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.cpSync(src, dest, { recursive: true, force: true })
  return true
}

function loadChromeAuth() {
  const script = path.join(
    process.cwd(),
    'scripts',
    '_extract_chrome_auth.py',
  )
  const raw = execFileSync('python', [script], { encoding: 'utf8' })
  return JSON.parse(raw)
}

if (fs.existsSync(profileDir)) fs.rmSync(profileDir, { recursive: true, force: true })
fs.mkdirSync(path.join(profileDir, 'Default'), { recursive: true })

copyDir(
  path.join(chromeDefault, 'Local Storage', 'leveldb'),
  path.join(profileDir, 'Default', 'Local Storage', 'leveldb'),
)

const idbRoot = path.join(chromeDefault, 'IndexedDB')
if (fs.existsSync(idbRoot)) {
  for (const name of fs.readdirSync(idbRoot)) {
    if (name.startsWith('http_localhost_5173')) {
      copyDir(
        path.join(idbRoot, name),
        path.join(profileDir, 'Default', 'IndexedDB', name),
      )
    }
  }
}

const auth = loadChromeAuth()
if (!auth.token) {
  throw new Error('Could not extract access_token from Chrome localStorage')
}

const context = await chromium.launchPersistentContext(profileDir, {
  headless: true,
  channel: 'chrome',
  viewport: { width: 1400, height: 900 },
})

await context.addInitScript(
  ({ token, user }) => {
    localStorage.setItem('access_token', token)
    if (user) localStorage.setItem('greencare-admin-user', JSON.stringify(user))
  },
  { token: auth.token, user: auth.user },
)

const page = context.pages()[0] ?? (await context.newPage())

await page.goto(`${ORIGIN}/`, {
  waitUntil: 'networkidle',
  timeout: 180_000,
})

if (page.url().includes('/login')) {
  throw new Error(`Not authenticated — landed on ${page.url()}`)
}

const result = await page.evaluate(async (reportId) => {
  const labels = {
    title: 'Course Work Report',
    brand: 'GreenCare',
    workDate: 'Work Date',
    markCount: 'Marks',
    markCountUnit: '',
    generatedAt: 'Generated',
    courseLabel: 'Course',
    marks: 'Marked Tasks',
    mapSection: 'Work Map',
    mapCaption: 'Numbers match the task list below',
    colNo: 'No',
    colWork: 'Task',
    colArea: 'Area',
    colGps: 'GPS',
    colDate: 'Date',
    noMarks: 'No tasks marked',
    coverFootLeft: 'Daejung Golf Engineering',
    coverFootRight: 'Auto-generated by GreenCare Admin',
    backLine1: 'This report was auto-generated by GreenCare Admin.',
    backLine2: 'Daejung Golf Engineering',
    pageFooter: 'GreenCare — Greenkeeping Work Report',
    areaGreen: 'Green',
    areaTee: 'Tee',
    areaFairway: 'Fairway',
    areaUnknown: '—',
    eyebrow: 'COURSE WORK REPORT',
    mapSubtitle: 'Pin numbers match the task list',
    backClose: 'End of report',
    statAreas: 'Work areas',
  }

  function openIDB() {
    return new Promise((resolve, reject) => {
      const req = indexedDB.open('greencare-map-reports', 2)
      req.onsuccess = () => resolve(req.result)
      req.onerror = () => reject(req.error)
    })
  }

  const db = await openIDB()
  const oldBuf = await new Promise((resolve, reject) => {
    const tx = db.transaction('pdfs', 'readonly')
    const req = tx.objectStore('pdfs').get(reportId)
    req.onsuccess = () => resolve(req.result ?? null)
    req.onerror = () => reject(req.error)
  })
  const oldSize =
    oldBuf instanceof Blob
      ? oldBuf.size
      : oldBuf instanceof ArrayBuffer
        ? oldBuf.byteLength
        : oldBuf
          ? 1
          : 0

  const imageDataUrl = await new Promise((resolve, reject) => {
    const tx = db.transaction('images', 'readonly')
    const req = tx.objectStore('images').get(reportId)
    req.onsuccess = () =>
      resolve(typeof req.result === 'string' ? req.result : null)
    req.onerror = () => reject(req.error)
  })
  db.close()

  const raw = localStorage.getItem('greencare-map-work-reports')
  const parsed = raw ? JSON.parse(raw) : null
  const reports = Array.isArray(parsed)
    ? parsed
    : Array.isArray(parsed?.state?.reports)
      ? parsed.state.reports
      : []
  const report = reports.find((r) => r.id === reportId)
  if (!report) throw new Error(`Report ${reportId} not in localStorage meta`)
  if (!imageDataUrl) throw new Error('Map image missing from IndexedDB')

  const { buildMapWorkPdf } = await import('/src/lib/mapWorkPdf.ts')
  const blob = await buildMapWorkPdf({
    courseName: report.courseName,
    workDate: report.workDate,
    marks: report.marks,
    mapImageDataUrl: imageDataUrl,
    courseBounds: report.courseBounds,
    labels,
    generatedAt: report.createdAt,
  })

  const bytes = Array.from(new Uint8Array(await blob.arrayBuffer()))
  return { oldSize, newSize: bytes.length, bytes }
}, REPORT_ID)

if (result.bytes?.length) {
  fs.writeFileSync(OUT, Buffer.from(result.bytes))
}

const summary = {
  reportId: REPORT_ID,
  course: 'Yangji Pine',
  workDate: '2026-07-21',
  oldSizeBytes: result.oldSize,
  newSizeBytes: result.newSize,
  oldSizeMB: +(result.oldSize / (1024 * 1024)).toFixed(2),
  newSizeMB: +(result.newSize / (1024 * 1024)).toFixed(2),
  reductionPct:
    result.oldSize > 0
      ? +((1 - result.newSize / result.oldSize) * 100).toFixed(1)
      : null,
  under20mb: result.newSize > 0 && result.newSize <= LIMIT,
  limitBytes: LIMIT,
  savedTo: OUT,
}

console.log(JSON.stringify(summary, null, 2))
await context.close()
